"""Render docs/assets/agent-demo/hero.gif, the README's opening animation.

The left side abridges docs/assets/agent-demo/hero-session.json, a real
Claude Code session with the MusubiCAD plugin. Every quoted fact is checked
against that transcript before anything is drawn.

The right side shows only real output:

- the actuator housing regenerated by `musubicad` at evenly spaced values
  between the old and new hub size (each step is applied with `musubicad
  patch`, so each one is verified before it is rendered with `musubicad
  preview`);
- `hero-preview.png`, the exact PNG the agent looked at, which must match
  the last regenerated step pixel for pixel;
- the URDF the agent exported, loaded in MuJoCo (frames from
  `render-urdf-mujoco.py`).

    musubicad export examples/robot_arm_assembly.ocad.d /tmp/arm/robot_arm.urdf
    MUJOCO_GL=osmesa python docs/assets/render-urdf-mujoco.py \
        /tmp/arm/robot_arm.urdf /tmp/arm/arm.gif
    python docs/assets/generate-hero-demo.py --arm-gif /tmp/arm/arm.gif

Needs Pillow and the `musubicad` binary (`--musubicad PATH` if it is not on
PATH).
"""

